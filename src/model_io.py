"""Model loading helpers."""

from __future__ import annotations

import pickle
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parents[1]
MODEL_DIR = PROJECT_ROOT / "models"


def load_model(filename: str, model_dir: Path | None = None) -> Any:
    """Load one trusted local pickle model artifact.

    Pickle files can execute code while loading. Only artifacts generated by this
    project or another trusted source should be placed in the model directory.
    """
    requested = Path(filename)
    if requested.name != filename or requested.suffix != ".sav":
        raise ValueError("Model filename must be a local .sav filename without path components.")

    directory = model_dir or MODEL_DIR
    path = directory / requested.name
    if not path.is_file():
        raise FileNotFoundError(
            f"Model file not found: {path}. "
            "Run 'python -m scripts.train_models' or restore the tracked model artifact."
        )

    with path.open("rb") as file:
        return pickle.load(file)
